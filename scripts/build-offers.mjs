#!/usr/bin/env node
/* ishur.io · build-offers
   ---------------------------------------------------------------------------
   config.js is the single source for prices and promotions. This script reads
   it (in a sandbox, exactly as the browser would) and writes the three places
   an AI assistant or a search engine reads "what does it cost / what is on
   offer right now":

     1. /offers.json                       machine-readable, linked from llms.txt
     2. llms.txt     between <!-- offers:start --> and <!-- offers:end -->
     3. index.html   between <!-- offers-ld:start --> and <!-- offers-ld:end -->
                     (JSON-LD Offer with validThrough), and the static
                     price table between <!-- price-static:start/end -->

   Which promos are public: a BUNDLES entry with an `until` date that has not
   passed yet (today: the two "מבצע חורף" bundles). Undated bundles (vip1990)
   are private link-only prices and are never published. PROMOS (friend / biz
   codes) are link-gated and never published either.

   Usage:
     node scripts/build-offers.mjs           write the three targets
     node scripts/build-offers.mjs --check   exit 1 if any target is stale
   Run it after every change to PRICE_TABLE, PLANS, HOSTESS or BUNDLES.
   ------------------------------------------------------------------------- */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const SITE = 'https://ishur.io';

/* ── load config.js the way a page does ─────────────────────────────────── */
const sandbox = { window: {}, console };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'config.js'), 'utf8'), sandbox, { filename: 'config.js' });
const C = sandbox.window.ISHUR_CONFIG;
if (!C || !C.PRICE_TABLE || !C.PLANS || !C.BUNDLES) {
  console.error('FAIL: config.js did not expose PRICE_TABLE / PLANS / BUNDLES');
  process.exit(2);
}

const ils = (n) => Number(n).toLocaleString('en-US');           // 1,790
const tiers = Object.keys(C.PRICE_TABLE).map(Number).sort((a, b) => a - b);
const planOrder = C.PLAN_ORDER || ['basic', 'pro', 'premium'];

/* ── public promos: dated + still live ──────────────────────────────────── */
const now = Date.now();
const promos = Object.entries(C.BUNDLES)
  .filter(([, b]) => b.until && Date.parse(b.until) >= now)
  .map(([key, b]) => {
    const plan = C.PLANS[b.plan] || {};
    const lo = Math.min(...b.guests), hi = Math.max(...b.guests);
    const host = b.hostesses === 1 ? 'דיילת אחת' : `${b.hostesses} דיילות`;
    return {
      id: key,
      name: b.note || 'מבצע',
      title: `${b.note || 'מבצע'}: ${b.label}`,
      price: b.total,
      priceCurrency: 'ILS',
      includes: `חבילת ${plan.name || b.plan} + ${host} באירוע`,
      guests_from: lo,
      guests_to: hi,
      description: `${b.note || 'מבצע'}: חבילת ${plan.name || b.plan} ${/^\d/.test(host) ? 'ו-' : 'ו'}${host} באירוע, לאירועים של ${lo} עד ${hi} רשומות, ב-${ils(b.total)} ₪ כולל מע"מ. באזור המרכז הנסיעות כלולות; מחוץ למרכז תוספת נסיעות ${ils(b.travel != null ? b.travel : 250)} ₪.`,
      validThrough: b.until,
      url: `${SITE}/?offer=${key}`
    };
  });

/* ── base price facts (always published) ────────────────────────────────── */
const packages = planOrder.map((k) => ({
  key: k,
  name: C.PLANS[k].name,
  from_price: C.PRICE_TABLE[tiers[0]][k],
  price_by_records: Object.fromEntries(tiers.map((t) => [String(t), C.PRICE_TABLE[t][k]])),
  includes: C.PLANS[k].features
}));
const hostess = (C.HOSTESS.tiers || []).map((t) => ({ hostesses: t.count, up_to_records: t.max, price: t.price }));

const offersJson = {
  source: 'Generated from https://ishur.io/config.js by scripts/build-offers.mjs. Prices in ILS, VAT included, one-time per event.',
  business: { name: 'ishur.io · אישורי הגעה', operator: 'ריצארד טומסקי, עוסק מורשה 322414905', url: SITE + '/', whatsapp: '+' + C.WHATSAPP_NUMBER },
  currency: 'ILS',
  pricing_model: 'תשלום אחד לאירוע לפי כמות רשומות (מספר טלפון אחד = רשומה אחת), בלי מנוי',
  from_price: Math.min(...packages.map((p) => p.from_price)),
  packages,
  hostesses: { tiers: hostess, travel_note: C.HOSTESS.travelNote },
  gifts: { label: C.GIFTS.label, live: !!C.GIFTS.live, guest_fee: `${C.GIFTS.guestPct}% + ${C.GIFTS.guestFixed} ₪ מהאורח`, host_fee: C.GIFTS.coupleFee },
  current_promotions: promos
};
const offersText = JSON.stringify(offersJson, null, 2) + '\n';

/* ── llms.txt section ───────────────────────────────────────────────────── */
const llmsLines = ['<!-- offers:start · generated by scripts/build-offers.mjs from config.js, do not edit by hand -->', '## Current offers (מבצעים פעילים)', ''];
if (promos.length) {
  for (const p of promos) llmsLines.push(`- ${p.description} בתוקף עד ${p.validThrough.slice(0, 10)}. להזמנה: ${p.url}`);
} else {
  llmsLines.push('- אין כרגע מבצע פעיל. המחירים הרגילים: החל מ-50 ₪ לאירוע.');
}
llmsLines.push('', `Machine-readable prices and offers: ${SITE}/offers.json`, '<!-- offers:end -->');
const llmsBlock = llmsLines.join('\n');

/* ── index.html JSON-LD block ───────────────────────────────────────────── */
const ld = {
  '@context': 'https://schema.org',
  '@graph': promos.map((p) => ({
    '@type': 'Offer',
    '@id': `${SITE}/#offer-${p.id}`,
    name: p.title,
    description: p.description,
    price: String(p.price),
    priceCurrency: 'ILS',
    validThrough: p.validThrough,
    availability: 'https://schema.org/InStock',
    url: p.url,
    itemOffered: { '@id': `${SITE}/#service` },
    seller: { '@id': `${SITE}/#org` }
  }))
};
const ldBlock = promos.length
  ? `<!-- offers-ld:start · generated by scripts/build-offers.mjs from config.js, do not edit by hand -->\n<script type="application/ld+json">\n${JSON.stringify(ld, null, 2)}\n</script>\n<!-- offers-ld:end -->`
  : `<!-- offers-ld:start · generated by scripts/build-offers.mjs from config.js, do not edit by hand -->\n<!-- offers-ld:end -->`;

/* ── index.html static price table ─────────────────────────────────────
   The live picker is drawn by JS; AI crawlers (GPTBot, ClaudeBot,
   PerplexityBot) do not run JS, so without this they see no prices at all. */
const head = planOrder.map((k) => `<th>${C.PLANS[k].name}</th>`).join('');
const rows = tiers.map((t) => `<tr><td>${t} רשומות</td>${planOrder.map((k) => `<td>${ils(C.PRICE_TABLE[t][k])} ₪</td>`).join('')}</tr>`).join('\n        ');
const priceBlock = `<!-- price-static:start · generated by scripts/build-offers.mjs from config.js, do not edit by hand -->
    <details class="pr-static">
      <summary>כל המחירים בטבלה אחת</summary>
      <table>
        <caption>מחיר לאירוע בשקלים, כולל מע״מ, תשלום אחד בלי מנוי. רשומה = מספר טלפון אחד. מעל 900 רשומות: הצעה אישית בוואטסאפ.</caption>
        <thead><tr><th>כמות רשומות</th>${head}</tr></thead>
        <tbody>
        ${rows}
        </tbody>
      </table>
      <p>דיילות באירוע (תוספת לכל חבילה): ${hostess.map((h) => `${h.hostesses === 1 ? 'דיילת אחת' : h.hostesses + ' דיילות'} ${ils(h.price)} ₪`).join(' · ')}. ${C.HOSTESS.travelNote}</p>
    </details>
    <!-- price-static:end -->`;

/* ── write / check ──────────────────────────────────────────────────────── */
function between(file, startRe, endMark, block) {
  const p = path.join(ROOT, file);
  const src = fs.readFileSync(p, 'utf8');
  const s = src.search(startRe), e = src.indexOf(endMark);
  if (s < 0 || e < 0 || e < s) throw new Error(`${file}: markers missing`);
  return { p, src, out: src.slice(0, s) + block + src.slice(e + endMark.length) };
}
const targets = [
  { p: path.join(ROOT, 'offers.json'), src: fs.existsSync(path.join(ROOT, 'offers.json')) ? fs.readFileSync(path.join(ROOT, 'offers.json'), 'utf8') : '', out: offersText },
  between('llms.txt', /<!-- offers:start/, '<!-- offers:end -->', llmsBlock),
  between('index.html', /<!-- offers-ld:start/, '<!-- offers-ld:end -->', ldBlock)
];
/* the second index.html block is applied on top of the first one's output */
{
  const t = targets[2];
  const s2 = t.out.search(/<!-- price-static:start/), e2 = t.out.indexOf('<!-- price-static:end -->');
  if (s2 < 0 || e2 < s2) throw new Error('index.html: price-static markers missing');
  t.out = t.out.slice(0, s2) + priceBlock + t.out.slice(e2 + '<!-- price-static:end -->'.length);
}
let stale = 0;
for (const t of targets) {
  const rel = path.relative(ROOT, t.p);
  if (t.src === t.out) { console.log(`up to date  ${rel}`); continue; }
  if (CHECK) { stale++; console.log(`STALE       ${rel}`); continue; }
  fs.writeFileSync(t.p, t.out);
  console.log(`written     ${rel}`);
}
console.log(`public promos: ${promos.map((p) => p.id).join(', ') || 'none'}`);
if (CHECK && stale) process.exit(1);

#!/usr/bin/env node
/* 22/11 round 7 Part B (Richard: "Yes, all messages"): builds every guest template in worker/templates/ in the six
   guest languages, from the line table templates/i18n/lines.json. For each template <name> and language <l>:
     templates/i18n/out/<name>_<l>.json    alone: the message in that language (Meta language = that language)
     templates/i18n/out/<name>_he<l>.json  pair: the Hebrew message, a blank line, then the translation (Meta language he);
                                           the translation's variables are renumbered after the Hebrew ones, so the
                                           sender passes the same values twice (see pairParams in guest-lang.js).
   Footer from guest-lang.js; buttons from the table. Same shape as the Hebrew files (submit through /api/meta-admin).
   Nothing is sent to Meta here.   node worker/scripts/translate-templates.mjs   (exit 1 = a line has no translation) */
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
import { GUEST_LANGS, guestFooter, templateLang } from '../guest-lang.js';

const DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'templates');
const T = JSON.parse(fs.readFileSync(path.join(DIR, 'i18n', 'lines.json'), 'utf8'));
const OUT = path.join(DIR, 'i18n', 'out');

const key = line => line.replace(/\{\{\d+\}\}/g, '{{#}}');
const fill = (tpl, nums) => { let i = 0; return tpl.replace(/\{\{#\}\}/g, () => '{{' + nums[i++] + '}}'); };
const missing = new Set();

export function translateBody(text, lang, shift = 0) {
  return text.split('\n').map(line => {
    if (!line.trim()) return line;
    const nums = [...line.matchAll(/\{\{(\d+)\}\}/g)].map(m => Number(m[1]) + shift);
    const e = T.lines[key(line)];
    if (!e || !e[lang]) { missing.add(key(line) + ' [' + lang + ']'); return line; }
    return fill(e[lang], nums);
  }).join('\n');
}

function button(b, lang, pair) {
  const e = T.buttons[b.text];
  if (!e || !e[lang]) { missing.add('button ' + b.text + ' [' + lang + ']'); return { ...b }; }
  const [full, short] = e[lang];
  let text = full;
  if (pair) text = [b.text + ' · ' + full, e.he_short + ' · ' + full, e.he_short + ' · ' + short].find(t => [...t].length <= 25) || short;
  return { ...b, text };
}

export function build(src, lang, mode) {
  const p = src.payload, pair = mode === 'pair';
  const body = p.components.find(c => c.type === 'BODY');
  const nVars = new Set([...body.text.matchAll(/\{\{(\d+)\}\}/g)].map(m => m[1])).size;
  const comps = p.components.map(c => {
    if (c.type === 'BODY') {
      const ex = c.example && c.example.body_text ? c.example.body_text[0] : null;
      const text = pair ? c.text + '\n\n' + translateBody(c.text, lang, nVars) : translateBody(c.text, lang);
      return { ...c, text, ...(ex ? { example: { body_text: [pair ? [...ex, ...ex] : ex] } } : {}) };
    }
    if (c.type === 'FOOTER') return { ...c, text: guestFooter({ mode, lang }) };
    if (c.type === 'BUTTONS') return { ...c, buttons: c.buttons.map(b => button(b, lang, pair)) };
    return { ...c };
  });
  const name = p.name + '_' + (pair ? 'he' : '') + lang;
  return {
    _note: `22/11 generated by scripts/translate-templates.mjs from ${p.name}.json (${pair ? 'Hebrew + ' : ''}${lang}). Translations unverified by native speakers. Do not edit by hand.`,
    channel: src.channel, method: src.method, path: src.path,
    ...(pair ? { pairParams: 'repeat' } : {}),
    payload: { ...p, name, language: templateLang({ mode, lang }), components: comps }
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  fs.mkdirSync(OUT, { recursive: true });
  for (const f of fs.readdirSync(OUT)) fs.unlinkSync(path.join(OUT, f));
  let n = 0;
  for (const f of fs.readdirSync(DIR).filter(f => f.endsWith('.json')).sort()) {
    const src = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
    if (T.skip.includes(src.payload.name)) continue;
    for (const lang of GUEST_LANGS) for (const mode of ['alone', 'pair']) {
      const t = build(src, lang, mode);
      fs.writeFileSync(path.join(OUT, t.payload.name + '.json'), JSON.stringify(t, null, 2) + '\n'); n++;
    }
  }
  if (missing.size) { console.log('FAIL no translation for:\n  ' + [...missing].join('\n  ')); process.exit(1); }
  console.log(`${n} templates written to templates/i18n/out`);
}
